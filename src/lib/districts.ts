const DISTRICT_BY_NAME = new Map(DISTRICTS.map((d) => [d.name, d]));

/** Определить район по тексту адреса. null если не нашли совпадений. */
export function detectDistrict(address: string | null | undefined): string | null {
  if (!address) return null;
  const lower = address.toLowerCase();
  for (const d of DISTRICTS) {
    for (const alias of d.aliases) {
      if (lower.includes(alias)) return d.name;
    }
  }
  return null;
}

/** Полная информация о районе по имени (color, aliases) */
export function districtMeta(name: string | null | undefined): District | null {
  if (!name) return null;
  return DISTRICT_BY_NAME.get(name) || null;
}

/** Шорткат: данные для prisma.address.create()/upsert() с авто-районом */
export function withDistrict(address: string): { address: string; district: string | null } {
  return { address, district: detectDistrict(address) };
}
