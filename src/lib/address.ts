/**
 * Утилиты для отображения адресов СПб/ЛО.
 * Все заявки обслуживаются только в Санкт-Петербурге и Ленобласти,
 * поэтому страна/регион — лишний шум. Показываем максимум:
 *   • для СПб → улица, дом, корпус, офис
 *   • для ЛО  → населённый пункт + улица, дом, корпус
 */

/**
 *   «Россия, Санкт-Петербург, улица Маяковского, 12»
 *     → «улица Маяковского, 12»
 *
 *   «Россия, Ленинградская область, Всеволожский район, Мурино, улица Шоссе в Лаврики, 59к1»
 *     → «Мурино, улица Шоссе в Лаврики, 59к1»
 */
export function shortenSpbAddress(full: string | null | undefined): string {
  if (!full) return "";
  return full
    .replace(/^\s*Россия\s*,\s*/i, "")
    .replace(/^\s*Санкт-Петербург\s*,\s*/i, "")
    .replace(/^\s*Ленинградская\s+область\s*,\s*/i, "")
    .replace(/^\s*[А-Яа-яЁё-]+\s+район\s*,\s*/i, "")
    .trim();
}
